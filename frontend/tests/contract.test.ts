// S1 契约漂移测试（阶段零F 的存在理由）——简报要求：
//  ① types.ts 必须是 openapi-typescript 生成物（真读文件，不是 git 空断言）；
//  ② `pnpm gen:api && pnpm typecheck` 链条可跑；
//  ③ 构造一次「后端字段改名」，必须真的观察到前端编译失败（不许写永真断言）。
// 纪律：临时产物只写 %TEMP%\dsh-redtrace-sdd\，不碰仓库里真实的 backend/openapi.json（只读）。
import { describe, it, expect } from 'vitest'
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

const FRONTEND = resolve()
const OPENAPI = resolve('../backend/openapi.json')
const TYPES = resolve('src/api/types.ts')

function pnpmCli(): string {
  const cli = process.env.npm_execpath
  if (!cli) throw new Error('npm_execpath 未设置：请通过 `pnpm test` 运行本套件，不要直接跑裸 vitest')
  return cli
}

/** 以当前 node + 调用本测试的 pnpm CLI 执行子命令，失败抛异常（含 stdout/stderr）。 */
function runPnpm(command: string): { ok: boolean; output: string } {
  try {
    const out = execFileSync(process.execPath, [pnpmCli(), ...command.split(' ')], {
      cwd: FRONTEND,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      maxBuffer: 16 * 1024 * 1024,
      env: process.env,
    })
    return { ok: true, output: out }
  } catch (e) {
    const err = e as { stdout?: string; stderr?: string; message: string }
    return { ok: false, output: `${err.stdout ?? ''}${err.stderr ?? ''}${err.message}` }
  }
}

describe('S1 契约漂移防护', () => {
  it('types.ts 是 openapi-typescript 生成物（头部标记 + 真读文件）', () => {
    const head = readFileSync(TYPES, 'utf8').slice(0, 400)
    expect(head).toMatch(/generated by openapi-typescript/i)
    expect(head).toMatch(/Do not make direct changes/i)
  })

  it('gen:api 幂等：连续两次生成的 types.ts 字节一致', () => {
    const a = runPnpm('gen:api')
    expect(a.ok, a.output).toBe(true)
    const first = readFileSync(TYPES)
    const b = runPnpm('gen:api')
    expect(b.ok, b.output).toBe(true)
    expect(readFileSync(TYPES).equals(first)).toBe(true)
  }, 90_000)

  it('链：pnpm gen:api && pnpm typecheck 在当前契约上通过', () => {
    const gen = runPnpm('gen:api')
    expect(gen.ok, gen.output).toBe(true)
    const tsc = runPnpm('typecheck')
    expect(tsc.ok, tsc.output).toBe(true)
  }, 90_000)

  it('字段改名演练：后端 SourceOut.publisher 改名 → typecheck 必须失败（红线检测）', () => {
    const dir = mkdtempSync(join(tmpdir(), 'dsh-redtrace-sdd-'))
    // I-6（review-F2）：恢复判据从「退出码 0」升级为「字节级一致」——
    // types.ts 永不手改纪律的执行面不能留漂移态；备份也用于并发/中断后的可验证还原。
    const backup = readFileSync(TYPES)
    try {
      // 1) 构造「后端改名后的 openapi」副本：publisher → publisher_renamed（真实文件不动）
      const spec = JSON.parse(readFileSync(OPENAPI, 'utf8'))
      const src = spec.components.schemas.SourceOut
      const renamedPath = join(dir, 'openapi-renamed.json')
      src.properties.publisher_renamed = src.properties.publisher
      delete src.properties.publisher
      src.required = src.required.map((k: string) => (k === 'publisher' ? 'publisher_renamed' : k))
      writeFileSync(renamedPath, JSON.stringify(spec), 'utf8')

      // 2) 用改名后的契约重新生成类型（写进 src/api/types.ts，随后必须恢复）
      const gen = execFileSync(
        process.execPath,
        ['node_modules/openapi-typescript/bin/cli.js', renamedPath, '-o', 'src/api/types.ts'],
        { cwd: FRONTEND, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] },
      )
      expect(gen + readFileSync(TYPES, 'utf8')).toContain('publisher_renamed')

      // 3) typecheck 必须失败——消费方代码引用 publisher 时编译期就该炸
      const tsc = runPnpm('typecheck')
      expect(
        tsc.ok,
        `契约漂移未被发现！后端把 SourceOut.publisher 改名后前端 typecheck 仍通过，` +
          `说明没有任何代码在编译期消费该字段（红线失效）。\n输出尾部：\n${tsc.output.slice(-1500)}`,
      ).toBe(false)
      // 失败原因必须是 publisher 相关，而不是顺手把编译搞崩了
      expect(tsc.output).toMatch(/publisher/)
    } finally {
      // 4) 恢复：用真实 openapi.json 重新生成，链条回到绿色；**逐字节比对确认还原**
      const restore = runPnpm('gen:api')
      expect(restore.ok, restore.output).toBe(true)
      const restored = readFileSync(TYPES)
      expect(
        restored.equals(backup),
        '演练后 types.ts 与演练前不一致：恢复不完整，仓库可能残留漂移态生成物（I-6）',
      ).toBe(true)
      rmSync(dir, { recursive: true, force: true })
    }
  }, 180_000)
})
